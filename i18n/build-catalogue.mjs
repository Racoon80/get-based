// Turn i18n/translations-<lang>.json into the runtime catalogues js/i18n/locales/ui-<lang>.ts.
// Usage: node i18n/build-catalogue.mjs
import fs from 'node:fs';
import path from 'node:path';

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const strings = new Set(JSON.parse(fs.readFileSync(path.join(root, 'i18n/strings.json'), 'utf8')));
// Text the app reads back from the DOM must stay English (see i18n/keep-english.json).
const keep = JSON.parse(fs.readFileSync(path.join(root, 'i18n/keep-english.json'), 'utf8')).strings;
const keepEnglish = en => keep.some(k => (k.startsWith('~') ? en.includes(k.slice(1)) : en === k));
for (const lang of ['de', 'fr']) {
  const file = path.join(root, `i18n/translations-${lang}.json`);
  // Reviewed terms in i18n/overrides-<lang>.json win over machine translations.
  const reviewed = path.join(root, `i18n/overrides-${lang}.json`);
  const all = { ...(fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, 'utf8')) : {}),
    ...(fs.existsSync(reviewed) ? JSON.parse(fs.readFileSync(reviewed, 'utf8')) : {}) };
  // Only strings the app still contains; identical translations add nothing.
  // Templates need enough fixed text to be specific; "{0} time" would match unrelated text.
  const specific = en => !/\{\d+\}/.test(en) || (en.replace(/\{\d+\}/g, '').match(/\p{L}/gu) || []).length >= 10;
  const entries = Object.entries(all).filter(([en, tr]) => strings.has(en) && tr && tr !== en && specific(en) && !keepEnglish(en))
    .sort(([a], [b]) => a.localeCompare(b));
  // One line: the catalogue is generated data, and the repo caps source files at 800 lines.
  const body = JSON.stringify(Object.fromEntries(entries));
  fs.writeFileSync(path.join(root, `js/i18n/locales/ui-${lang}.ts`),
    `// Generated by i18n/build-catalogue.mjs from i18n/translations-${lang}.json. Do not edit by hand.\n` +
    `import type { UiCatalogue } from '../dom-translate.js';\n\nexport const ui: UiCatalogue = ${body};\n`);
  console.log(lang, entries.length);
}
